import { startOfSwedishDay, swedishDateKey, swedishDaysBetween } from '@eken/shared'

describe('svensk kalenderdag för hyresavier', () => {
  it.each([
    ['2026-09-23T21:59:59Z', '2026-09-23', '2026-09-22T22:00:00.000Z'],
    ['2026-09-23T22:00:00Z', '2026-09-24', '2026-09-23T22:00:00.000Z'],
    ['2026-01-31T22:59:59Z', '2026-01-31', '2026-01-30T23:00:00.000Z'],
    ['2026-01-31T23:00:00Z', '2026-02-01', '2026-01-31T23:00:00.000Z'],
    ['2026-12-31T23:00:00Z', '2027-01-01', '2026-12-31T23:00:00.000Z'],
    ['2026-03-29T00:30:00Z', '2026-03-29', '2026-03-28T23:00:00.000Z'],
    ['2026-03-29T01:30:00Z', '2026-03-29', '2026-03-28T23:00:00.000Z'],
    ['2026-03-29T22:00:00Z', '2026-03-30', '2026-03-29T22:00:00.000Z'],
    ['2026-10-25T00:30:00Z', '2026-10-25', '2026-10-24T22:00:00.000Z'],
    ['2026-10-25T01:30:00Z', '2026-10-25', '2026-10-24T22:00:00.000Z'],
    ['2026-10-25T23:00:00Z', '2026-10-26', '2026-10-25T23:00:00.000Z'],
  ])('%s har dag %s och rätt DB-gräns', (now, day, midnight) => {
    expect(swedishDateKey(new Date(now))).toBe(day)
    expect(startOfSwedishDay(new Date(now)).toISOString()).toBe(midnight)
  })

  it.each([
    ['2026-09-23T00:00:00Z', '2026-09-22T21:59:59Z', -1],
    ['2026-09-23T00:00:00Z', '2026-09-22T22:00:00Z', 0],
    ['2026-09-23T00:00:00Z', '2026-09-23T21:59:59Z', 0],
    ['2026-09-23T00:00:00Z', '2026-09-23T22:00:00Z', 1],
    ['2026-09-22T22:00:00Z', '2026-09-23T21:59:59Z', 0],
    ['2026-03-28T23:00:00Z', '2026-03-29T22:00:00Z', 1],
    ['2026-10-24T22:00:00Z', '2026-10-25T23:00:00Z', 1],
    ['2026-12-31T00:00:00Z', '2026-12-31T23:00:00Z', 1],
  ])('%s → %s räknar %s kalenderdagar', (from, to, days) => {
    expect(swedishDaysBetween(new Date(from), new Date(to))).toBe(days)
  })
})
